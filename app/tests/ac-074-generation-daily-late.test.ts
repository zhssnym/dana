/*
AC-074: given daily due 2026-07-20 completed 2026-07-24, then the successor is
due 2026-07-25.

Asserted by its content rather than at the dates it names, by the section 12
ruling of 2026-08-10. The content is 8.5's fourth worked consequence, daily
late with no pile-up: a daily rule left unclosed for four days has four
instances behind it, and closing it once produces exactly one successor, on
tomorrow, not four rows catching the series up. cutoff =
max(due_date, current_date(actor.tz)) is today, and the next daily instance
strictly after today is tomorrow.

This is the criterion that catches the loop. Generation reads naturally as
"advance the series until it is current", and an engine written that way
passes AC-072 (one step) and AC-073 (a weekly rule where two steps and one
step are the same answer for the last row) and then leaves four overdue rows
here, or one row after inserting three it also inserted. The row count is
therefore asserted as hard as the date is, and it is asserted against the
whole series rather than against what the response reported, because an
implementation that inserts four and returns the last one reports something
perfectly plausible.

The interval is four days rather than one so that a pile-up and a correct
answer cannot coincide, and so that the count discriminates: four missed
instances, one successor.

Spec: 8.5 (the cutoff and the fourth worked consequence, "nothing is ever
generated by the passage of time"), 5.1, 7.6 (the transition and its tz
parameter, ruled 2026-08-10), 4.11 (FREQ=DAILY).
*/
import { afterAll, beforeAll, describe, expect, test } from 'vitest'

import { startAuthTestApp } from './auth-harness.js'
import type { AuthTestApp } from './auth-harness.js'
import { Cast, createFolder } from './folders-harness.js'
import type { Actor } from './folders-harness.js'
import {
  expectSweptTasks,
  expectTaskInvariants,
  requireTaskRow,
} from './tasks-harness.js'
import {
  requireGenerated,
  requireOneSuccessor,
  seedRecurringTask,
  seriesRows,
  transitionRecurringOk,
} from './recurrence-harness.js'
import type { RecurringFixture } from './recurrence-harness.js'
import { middayZone, shiftDate, todayIn } from './views-harness.js'

let app: AuthTestApp
const cast = new Cast(['owner'], 'p6')

const tz = middayZone()

interface Stage {
  owner: Actor
  folderId: string
}
let staged: Stage | undefined
const taskIds: string[] = []

async function stage(): Promise<Stage> {
  if (staged === undefined) {
    const [owner] = await cast.of(app)
    if (owner === undefined) throw new Error('cast must produce one actor')
    const folderId = await createFolder(owner, 'p6 ac074 daily')
    staged = { owner, folderId }
  }
  return staged
}

/** A daily rule four days overdue: 8.5's "daily due 2026-07-20, completed
 * 2026-07-24" with the clock left alone. */
async function occurrence(label: string): Promise<RecurringFixture> {
  const { owner, folderId } = await stage()
  const dueDate = shiftDate(todayIn(tz), -4)
  const fixture = await seedRecurringTask(app.db, owner, {
    folderId,
    title: `p6 ac074 ${label}`,
    dueDate,
    rule: 'FREQ=DAILY',
  })
  taskIds.push(fixture.taskId)
  return fixture
}

beforeAll(async () => {
  app = await startAuthTestApp()
}, 60_000)

afterAll(async () => {
  if ((app as AuthTestApp | undefined) === undefined) return
  await cast.cleanup(app.db)
  await app.close()
})

describe('AC-074: a daily rule closed late produces tomorrow, once', () => {
  test('AC-074: the successor is due tomorrow', async () => {
    const { owner } = await stage()
    const fixture = await occurrence('successor')
    const today = todayIn(tz)

    const body = await transitionRecurringOk(
      owner,
      fixture.taskId,
      'complete',
      tz,
      'completing a four-day-old daily occurrence is allowed (spec 5.1)',
    )
    const generated = requireGenerated(
      body,
      'the completion generates the next instance',
    )
    const successor = await requireOneSuccessor(
      app.db,
      fixture.seriesId,
      fixture.taskId,
      'a four-day gap still generates exactly one row',
    )
    taskIds.push(successor.id)

    expect(
      String(successor.due_date),
      `8.5: cutoff is today for an overdue row, and the next daily instance strictly after today is tomorrow. Due ${fixture.dueDate}, completed today (${today}) in ${tz}`,
    ).toBe(shiftDate(today, 1))
    expect(generated.due_date, 'the wire agrees with the row').toBe(
      successor.due_date,
    )
  })

  test('AC-074: four missed days do not become four rows', async () => {
    const { owner } = await stage()
    const fixture = await occurrence('no pile-up')
    await transitionRecurringOk(
      owner,
      fixture.taskId,
      'complete',
      tz,
      'the completion is accepted (spec 5.1)',
    )
    const series = await seriesRows(app.db, fixture.seriesId)
    for (const row of series) taskIds.push(row.id)

    expect(
      series.map((row) => `${String(row.due_date)} ${String(row.status)}`),
      '8.5: nothing is ever generated by the passage of time, so a missed occurrence snowballs rather than backfilling. One transition inserts one row, whatever the gap',
    ).toHaveLength(2)
    expect(
      series.filter((row) => row.status === 'pending'),
      'INV-7: one pending row per series, which a catch-up loop breaks on its second insert',
    ).toHaveLength(1)
    expect(
      series.filter((row) => row.recurrence_rule !== null),
      '8.5 puts the rule on the current occurrence alone',
    ).toHaveLength(1)
  })

  test('AC-074 adversarial: the second close advances one day, not back to the start', async () => {
    const { owner } = await stage()
    const fixture = await occurrence('second close')
    await transitionRecurringOk(
      owner,
      fixture.taskId,
      'complete',
      tz,
      'the first completion is accepted (spec 5.1)',
    )
    const successor = await requireOneSuccessor(
      app.db,
      fixture.seriesId,
      fixture.taskId,
      'the first completion generated one successor',
    )
    taskIds.push(successor.id)

    // The successor is due tomorrow and closed today, that is, early. 8.5
    // re-anchors on it, so cutoff is its own date and the next instance is
    // the day after it, never today plus one again.
    const second = await transitionRecurringOk(
      owner,
      successor.id,
      'complete',
      tz,
      'closing the successor early is allowed (spec 5.1)',
    )
    const third = requireGenerated(second, 'the second close generates too')
    taskIds.push(String(third.id))
    expect(
      third.due_date,
      '8.5 evaluates with DTSTART = the current occurrence\'s due_date, so a series closed early keeps stepping forward from its own dates rather than restarting from today',
    ).toBe(shiftDate(String(successor.due_date), 1))
    expect(
      (await requireTaskRow(app.db, successor.id)).recurrence_rule,
      'and the rule moves on again',
    ).toBeNull()
  })

  test('AC-074: invariants hold afterwards', async () => {
    const { owner, folderId } = await stage()
    expectSweptTasks(taskIds)
    await expectTaskInvariants(app.db, taskIds, [folderId], [owner.id])
  })
})
