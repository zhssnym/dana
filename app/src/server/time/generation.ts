/*
8.5's generation: the one thing that creates the next occurrence of a series.

**Exactly one trigger, and it is not time.** 8.5 is explicit that nothing is
ever generated by the passage of time and that there is no recurrence
background job. The successor exists because the current occurrence left
pending, through complete or abandon, and that is the only call site: 5.1's
table puts it on those two rows and 8.3's guarded update makes the winning
transition the only one that reaches it. A missed occurrence just snowballs
in My Day until someone acts on it.

**The caller owns the transaction.** This function takes an executor and
opens nothing, the shape of deleteAccountData(tx, userId): 8.3 requires
the insert to commit with the status change or not at all, because a
successor without its completion, or a completion without its successor, is
a series a user cannot repair. It also needs no lock of its own, the guarded
UPDATE that decided the caller won having already taken the row.

**The zone is the request's, not the row's.** cutoff = max(due_date,
current_date(actor.tz)), and 8.5 binds actor.tz to the zone of the request
that made the transition. 7.6 carries it as a parameter on complete and
abandon, and 8.1 reserves
users.timezone for reminder fire instants alone: a task completed by a
colleague in Auckland must generate against the day it is where the request
came from, and the column on the actor's row is the one wrong answer within
reach. So the zone arrives as an argument here and this module never reads a
user row.

What the successor carries is 8.5's list and is copied from the row itself
rather than from a serialization of it, so a column added later cannot be
silently dropped by this file: folder, title, notes, assignee, importance,
due_time, the rule, the series, and created_by, which stays the original
creator rather than becoming the actor. Status is pending. The steps come
across unticked, and so does the reminder, whose instant is recomputed for the
successor's own due date rather than copied. My Day entries are never copied,
which 8.5 states and 8.2 explains: a pull is one decision about one occurrence.
*/
import { sql } from 'drizzle-orm'

import { assertCalendarDate, compareDates } from './calendar-date.js'
import type { CalendarDate } from './calendar-date.js'
import { rowsOf } from '../database.js'
import type { Executor } from '../database.js'
import { nextInstance } from './recurrence.js'
import { copyReminderToSuccessor } from './reminder-recompute.js'
import { today } from './today.js'

/** What generation did, for the caller that has to answer 7.6's envelope. */
export type GenerationOutcome =
  /** A successor exists. generated_task is this row. */
  | {
      readonly kind: 'generated'
      readonly successorId: string
      readonly dueDate: CalendarDate
    }
  /** UNTIL bounded the series out. 8.5: the rule stays on the row, which is
   * what lets a restore resume the series later (5.1's second branch). */
  | { readonly kind: 'exhausted' }
  /** The row carries no rule, so there was nothing to generate. Not an
   * error: three of the four transitions reach a row like this, and complete
   * reaches one whenever the task simply does not repeat. */
  | { readonly kind: 'not_recurring' }

export interface GenerationRequest {
  /** The occurrence that just left pending. */
  readonly taskId: string
  /** The IANA zone of the request that made the transition (8.5, 8.1). */
  readonly tz: string
  /** The instant today is read at, defaulted like today() so a caller with
   * an opinion about where the clock comes from can say so. */
  readonly at?: Date
}

/**
 * 8.5's generate_successor, run inside the caller's transaction.
 *
 * Call it in the winning branch of a complete or abandon transition, after
 * the guarded UPDATE reported one row, and only there. It reads the task
 * itself, so the caller passes an id and a zone and nothing else.
 */
export async function generateSuccessor(
  tx: Executor,
  request: GenerationRequest,
): Promise<GenerationOutcome> {
  // The due date is read through to_char because the two drivers disagree
  // about a DATE column (PGlite renders a string, node-postgres parses OID
  // 1082 into a JS Date), and an instant here is the defect 4.11's floating
  // storage exists to prevent. The domain module reads its dates the same way.
  const found = await rowsOf(
    tx,
    sql`SELECT to_char(due_date, 'YYYY-MM-DD') AS due_date, recurrence_rule
          FROM tasks WHERE id = ${request.taskId}::uuid`,
  )
  const row = found[0]
  if (row === undefined) {
    throw new TypeError(
      `generateSuccessor was given a task that does not exist: ${request.taskId}`,
    )
  }
  const rule = row.recurrence_rule === null ? null : String(row.recurrence_rule)
  if (rule === null) return { kind: 'not_recurring' }
  if (row.due_date === null) {
    // 4.5 makes this a CHECK (a rule requires a due_date) and 8.4's cascade
    // clears the rule with the date, so this is corruption rather than a
    // state to handle: the anchor 8.5 evaluates from does not exist.
    throw new TypeError(
      `task ${request.taskId} carries a recurrence_rule with no due_date, which 4.5 forbids`,
    )
  }

  const dueDate = assertCalendarDate(row.due_date, 'due_date')
  const currentDate = today(request.tz, request.at)
  // The whole of the late-and-early behavior 8.5's four worked examples pin.
  // A late completion cuts off at today, so the slots it slept through are
  // skipped and the calendar shows an honest gap; an early one cuts off at
  // the due date, so finishing on Saturday does not pull Monday's chore
  // forward a week.
  const cutoff = compareDates(dueDate, currentDate) >= 0 ? dueDate : currentDate
  const nextDue = nextInstance(rule, dueDate, cutoff)
  if (nextDue === null) return { kind: 'exhausted' }

  const inserted = await rowsOf(
    tx,
    sql`INSERT INTO tasks (folder_id, title, notes, important, due_date,
                           due_time, recurrence_rule, series_id, assignee_id,
                           created_by, status)
        SELECT folder_id, title, notes, important, ${nextDue}::date,
               due_time, recurrence_rule, series_id, assignee_id,
               created_by, 'pending'
          FROM tasks WHERE id = ${request.taskId}::uuid
        RETURNING id`,
  )
  const successor = inserted[0]
  if (successor === undefined) {
    throw new TypeError(
      `the successor of ${request.taskId} was not inserted, and 8.5 has no state where that is a normal outcome`,
    )
  }
  const successorId = String(successor.id)

  // 8.5: the steps come across with done = false, which is the column
  // default, and in the same order, which position carries (4.6 orders by
  // position then id and allows gaps, so copying the numbers preserves it).
  await tx.execute(
    sql`INSERT INTO steps (task_id, title, position)
        SELECT ${successorId}::uuid, title, position
          FROM steps WHERE task_id = ${request.taskId}::uuid`,
  )

  /*
  8.5's reminder arm: "if reminder exists on t, insert reminder on s with
  same mode and value, fire_at recomputed per 8.6". It sits between the step
  copy above and the rule handover below, and it reads the assignee's zone rather than the
  request's, which is 8.6's rule and not this function's. The successor row
  already carries the assignee and the due_time it was copied with, so the
  computation is over the successor and needs nothing passed to it: the whole
  of it, including which of 8.6's two zone arms applies, is
  copyReminderToSuccessor's.
  */
  await copyReminderToSuccessor(tx, request.taskId, successorId, request.at)


  // 8.5: the rule lives only on the current occurrence, and the current
  // occurrence is now the successor. Last, because the insert above reads
  // the rule off this row.
  await tx.execute(
    sql`UPDATE tasks SET recurrence_rule = NULL, updated_at = now()
        WHERE id = ${request.taskId}::uuid`,
  )

  return { kind: 'generated', successorId, dueDate: nextDue }
}
